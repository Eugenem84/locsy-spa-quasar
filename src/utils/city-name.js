// Отображаемые названия городов.
// В справочнике GeoNames (RU) названия приходят вместе с регионом:
// «Новосибирск (Новосибирская область)», «Казан (Республика Татарстан)» —
// в списке городов это слишком длинно, поэтому служебные слова сокращаем.
const SHORT_FORMS = {
  республика: 'Респ',
  область: 'обл.'
}

// Слова ищем без пробелов и скобок (скобки остаются на месте),
// а служебные символы (кавычки, запятые, точки) при сравнении отбрасываем.
const WORD_RE = /[^\s()]+/g
const NON_LETTER_RE = /[^a-zа-яё]/g

/**
 * Сокращает служебные слова в названии города:
 * «Новосибирск (Новосибирская область)» → «Новосибирск (Новосибирская обл.)»,
 * «Казан (Республика Татарстан)» → «Казан (Респ Татарстан)».
 * @param {string} [name] исходное название из API
 * @returns {string} название для отображения
 */
export function formatCityName(name) {
  if (!name) return ''

  return String(name).replace(WORD_RE, (word) => {
    const key = word.toLowerCase().replace(NON_LETTER_RE, '')
    return SHORT_FORMS[key] ?? word
  })
}
